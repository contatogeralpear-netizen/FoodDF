 await expect(page.locator('.product-card')).toHaveCount(2);
 await page.getByRole('button',{name:'Limpar busca'}).click();
 await page.getByRole('button',{name:'Adicionar Brasa Bacon',exact:true}).click();
 await page.reload();
 await expect(page.locator('.product-card').filter({hasText:'Brasa Bacon'}).getByRole('button',{name:'Aumentar Brasa Bacon'})).toBeVisible();
 await page.screenshot({path:`artifacts/menu-${info.project.name}.png`,fullPage:true});
